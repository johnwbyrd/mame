// ============================================================================
// DEFINE_ZBC Macro - Generates complete ZBC variant in a single line
// ============================================================================
//
// This macro generates:
// 1. A derived class (zbc_<name>_state) inheriting from zbc_state template
// 2. ROM definition (empty for these systems)
// 3. MAME machine registration (makes it available via command line)
//
// Parameters:
//   cpu_class: CPU device class for template instantiation (e.g., m6502_device)
//   cpu_type: MAME device type macro for machine_config (e.g., M6502)
//   short_name: Machine name suffix, creates "zbc<short_name>" (e.g., 6502 → zbc6502)
//   display_name: Human-readable name for UI (e.g., "MOS 6502")
//   ...: Optional template parameter overrides (load_addr, cpu_speed, vram_addr)
//        Example: DEFINE_ZBC(..., ..., ..., ..., 0x1000, 8000000) sets LOAD_ADDR=0x1000, CPU_SPEED=8MHz
#define DEFINE_ZBC(cpu_class, cpu_type, short_name, display_name, ...)         \
	namespace {                                                                \
	class zbc_##short_name##_state                                             \
	    : public zbc_state<cpu_class, ##__VA_ARGS__> {                         \
	  public:                                                                  \
		using zbc_state<cpu_class, ##__VA_ARGS__>::zbc_state;                  \
		void machine_config(machine_config &config) { zbc(config, cpu_type); } \
	};                                                                         \
	}                                                                          \
	ROM_START(zbc##short_name)                                                 \
	ROM_END                                                                    \
	COMP(2025, zbc##short_name, 0, 0, machine_config, 0,                       \
	     zbc_##short_name##_state, empty_init, "MAME",                         \
	     "Zero Board Computer - " display_name, MACHINE_NO_SOUND_HW | MACHINE_SUPPORTS_SAVE)

